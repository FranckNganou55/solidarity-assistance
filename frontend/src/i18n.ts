export const dictionaries: Record<Lang, Dict> = { fr, en };

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  // Keep UI copy in both dictionaries. English is the neutral fallback so a missing
  // English key never silently leaves French text on an English screen.
  let value = dictionaries[lang][key] ?? dictionaries.en[key] ?? dictionaries.fr[key] ?? key;
  if (vars) Object.entries(vars).forEach(([k, v]) => { value = value.replace(`{${k}}`, String(v)); });
  return value;
}
